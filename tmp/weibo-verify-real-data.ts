import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { assertWeiboCollectionCanSubmit, assertWeiboCollectionHasNoDuplicates } from "../packages/weibo-drama-automation/src/automation/existing-collection.js";
const info = JSON.parse(await readFile(new URL("./weibo-24812-evidence.json", import.meta.url), "utf8"));
assert.equal(info.video_list.length, 122);
